function metinKopyala(t) {
  const bitti = function () { bildir("Panoya kopyalandı."); };
  if (navigator.clipboard && window.isSecureContext) navigator.clipboard.writeText(t).then(bitti, function () { yedekKopyala(t, false); });
  else yedekKopyala(t, false);
}
function yedekKopyala(icerik, html) {
  const el = document.createElement(html ? "div" : "textarea");
  if (html) { el.innerHTML = icerik; el.contentEditable = "true"; } else el.value = icerik;
  el.style.cssText = "position:fixed; left:-9999px; top:0";
  document.body.appendChild(el);
  if (html) { const r = document.createRange(); r.selectNodeContents(el); const sel = window.getSelection(); sel.removeAllRanges(); sel.addRange(r); } else el.select();
  let ok = false;
  try { ok = document.execCommand("copy"); } catch (e) { ok = false; }
  el.remove();
  bildir(ok ? "Panoya kopyalandı." : "Kopyalanamadı; metni seçip Ctrl+C ile kopyalayınız.", ok ? "" : "hata");
}
function ebysHtml() {
  const kok = $("docArea").cloneNode(true);
  if (appData.ui.doc === "olur") kok.querySelectorAll(".ebys-strip").forEach(function (x) { x.remove(); });
  kok.querySelectorAll("table").forEach(function (t) { t.setAttribute("style", (t.getAttribute("style") || "") + ";border-collapse:collapse;width:100%"); t.setAttribute("border", t.classList.contains("plain") ? "0" : "1"); t.setAttribute("cellpadding", "4"); });
  kok.querySelectorAll("th,td").forEach(function (c) {
    const plain = c.closest("table.plain");
    c.setAttribute("style", (c.getAttribute("style") || "") + (plain ? ";border:0" : ";border:1px solid #000") + ";padding:3px 5px;vertical-align:middle" + (c.tagName === "TH" ? ";font-weight:bold;text-align:center" : ""));
  });
  kok.querySelectorAll("h1").forEach(function (h) { h.setAttribute("style", "text-align:center;font-size:12pt"); });
  kok.querySelectorAll("p.ind").forEach(function (p) { p.setAttribute("style", "text-indent:1.25cm;text-align:justify"); });
  kok.querySelectorAll(".olur-fit").forEach(function (x) { x.style.zoom = ""; });
  return '<div style="font-family:\'Times New Roman\',serif;font-size:11pt">' + Array.from(kok.querySelectorAll(".sheet")).map(function (s) { return s.innerHTML; }).join("<br>") + "</div>";
}
function ebysKopyala() {
  const html = ebysHtml();
  const duz = $("docArea").innerText;
  if (navigator.clipboard && window.ClipboardItem && window.isSecureContext) {
    navigator.clipboard.write([new ClipboardItem({ "text/html": new Blob([html], { type: "text/html" }), "text/plain": new Blob([duz], { type: "text/plain" }) })])
      .then(function () { bildir("Belge biçimiyle panoya kopyalandı (EBYS / Word'e yapıştırabilirsiniz)."); }, function () { yedekKopyala(html, true); });
  } else yedekKopyala(html, true);
}
