function dersEtiket(st, ders) {
  const u = dersUnits(st.units, ders);
  if (!u.length) return "–";
  return ders === "TR" ? u.map(function (x) { return UNIT[x].sira + ". ÖA"; }).join(", ") : u.map(function (x) { return UNIT[x].sira; }).join(", ") + ". tema";
}
function grupTarih(g) {
  const p = grupPlanCache(g);
  const bas = p.oturumlar.length ? p.oturumlar[0].tarih : isoParse(g.baslama || appData.settings.baslama);
  return { bas: bas, bit: p.bitis || isoParse(appData.settings.bitis) };
}
function gunDagilimMetni(g) { return GUN_KEYS.filter(function (k) { return sayi(g.gunler[k]); }).map(function (k) { return GUN_AD[k] + " " + g.gunler[k] + " saat"; }).join(", ") || "–"; }
function sheet(ic, sinif) { return '<div class="sheet ' + (sinif || "") + '">' + ic + "</div>"; }
function bosSatir(n, kolon) { let h = ""; for (let i = 0; i < n; i++) h += "<tr>" + new Array(kolon + 1).join("<td>&nbsp;</td>") + "</tr>"; return h; }
function izlemeOzet(g, uid) {
  const ogr = izlemeOgrencileri(g, uid), u = UNIT[uid];
  let e = 0, n = 0, pg = 0;
  ogr.forEach(function (st) { u.ciktilar.forEach(function (c) { n++; if (st.izleme[c.kod] === "E") e++; }); if (st.pg[uid] && st.pg[uid].puan) pg++; });
  return { ogr: ogr.length, pct: n ? Math.round(100 * e / n) : 0, pg: pg };
}

