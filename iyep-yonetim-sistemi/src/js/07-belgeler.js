function yerTut(t) {
  const s = appData.settings;
  return String(t || "").replace(/\{yil\}/g, s.yil || "........").replace(/\{okul\}/g, s.okul || "........")
    .replace(/\{oba\}/g, tarihVeyaNokta(s.obaTarihi)).replace(/\{oda\}/g, tarihVeyaNokta(s.odaTarihi))
    .replace(/\{baslama\}/g, tarihVeyaNokta(s.baslama)).replace(/\{bitis\}/g, tarihVeyaNokta(s.bitis));
}
function tutanak(key) {
  const d = TUTANAK_VARSAYILAN[key], k = appData.settings.tutanak[key] || {};
  return { giris: k.giris != null ? k.giris : d.giris, baslik: k.baslik != null ? k.baslik : d.baslik, maddeler: Array.isArray(k.maddeler) ? k.maddeler : d.maddeler };
}
function tutanakGiris(key) { const g = tutanak(key).giris; return g && g.trim() ? '<p class="ind">' + esc(yerTut(g)).replace(/\n/g, "<br>") + "</p>" : ""; }
